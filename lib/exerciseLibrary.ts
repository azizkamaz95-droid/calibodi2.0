export function getExerciseById(id: string): Exercise | undefined {
  return exercises.find(e => e.id === id);
}

export function getExercisesByCategory(cat: ExerciseCategory): Exercise[] {
  return exercises.filter(e => e.category === cat);
}

export function getAdaptedExercise(exercise: Exercise, injuries: InjuryZone[]): Exercise {
  const hasConflict = exercise.injuryContraindications.some(z => injuries.includes(z));
  if (hasConflict && exercise.replacement) {
    const replacement = getExerciseById(exercise.replacement);
    if (replacement) return replacement;
  }
  return exercise;
}

export function getExercisesForLevel(level: Difficulty): Exercise[] {
  const diffMap: Record<Difficulty, Difficulty[]> = {
    beginner: ['beginner'],
    intermediate: ['beginner', 'intermediate'],
    advanced: ['beginner', 'intermediate', 'advanced'],
  };
  return exercises.filter(e => diffMap[level].includes(e.difficulty) && e.category !== 'warmup' && e.category !== 'cooldown');
}
